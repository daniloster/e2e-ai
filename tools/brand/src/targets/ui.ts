// The app's UI art: transparent images at 1x/2x/3x plus the module that `require`s them (React
// Native picks the scale). Art: uiArt.ts.
import { APP_BRAND } from '../paths';
import { renderPng } from '../png';
import type { BrandTarget, FileMap } from '../types';
import { UI_ART_NAMES, uiArtSources } from '../uiArt';

export const UI_ART_DIR = `${APP_BRAND}/ui`;
export const UI_SCALES: readonly number[] = Object.freeze([1, 2, 3]);

type Entry = readonly [path: string, contents: Uint8Array | string];

function fileName(name: string, scale: number): string {
  return `${name}${scale === 1 ? '' : `@${scale}x`}.png`;
}

/** The generated apps/mobile/src/brand/ui/index.ts text. */
export function uiArtModuleSource(): string {
  const keys = UI_ART_NAMES.map((name) => `  '${name}',`).join('\n');
  const requires = UI_ART_NAMES.map((name) => `  ${name}: require('./${name}.png'),`).join('\n');
  const sizes = uiArtSources()
    .map((s) => `  ${s.name}: { width: ${s.widthPt}, height: ${s.heightPt} },`)
    .join('\n');
  return `// Generated by tools/brand (npm run brand -- --targets ui) - do not edit.
/* eslint-disable @typescript-eslint/no-require-imports -- React Native static image requires */
import type { ImageSourcePropType } from 'react-native';

/** Every UI image, in write order. */
export const UI_ART_KEYS = [
${keys}
] as const;

export type UiArt = (typeof UI_ART_KEYS)[number];

/** Transparent images; @2x and @3x files sit next to each one. Glyphs are ink, for tintColor. */
export const UI_ART: Readonly<Record<UiArt, ImageSourcePropType>> = {
${requires}
};

/** Size of each image in points. */
export const UI_ART_SIZE: Readonly<
  Record<UiArt, { width: number; height: number }>
> = {
${sizes}
};
`;
}

/** One PNG per source and scale, then index.ts. */
export function buildUiFiles(): FileMap {
  const entries: Entry[] = uiArtSources().flatMap((source) =>
    UI_SCALES.map((scale): Entry => [
      `${UI_ART_DIR}/${fileName(source.name, scale)}`,
      renderPng(source.svg, source.widthPt * scale, { heightPx: source.heightPt * scale }),
    ]),
  );
  entries.push([`${UI_ART_DIR}/index.ts`, uiArtModuleSource()]);
  return new Map(entries);
}

export const uiTarget: BrandTarget = Object.freeze({ id: 'ui', build: buildUiFiles });
