import { describe, expect, it } from 'vitest';

import { readPngInfo } from '../png';
import type { FileMap } from '../types';
import { UI_ART_NAMES, uiArtSources } from '../uiArt';
import { buildUiFiles, UI_ART_DIR, UI_SCALES, uiArtModuleSource } from './ui';

const SUFFIXES = [
  ['', 1],
  ['@2x', 2],
  ['@3x', 3],
] as const;

function png(files: FileMap, path: string): Uint8Array {
  const value = files.get(path);
  if (!(value instanceof Uint8Array)) throw new Error(`no PNG at ${path}`);
  return value;
}

describe('ui target', () => {
  const files = buildUiFiles();

  it('writes into the app brand folder at 1x, 2x and 3x', () => {
    expect(UI_ART_DIR).toBe('apps/mobile/src/brand/ui');
    expect(UI_SCALES).toEqual([1, 2, 3]);
    expect(Object.isFrozen(UI_SCALES)).toBe(true);
  });

  it('writes each image at 1x, 2x and 3x, then the index module', () => {
    const expected = UI_ART_NAMES.flatMap((name) =>
      SUFFIXES.map(([suffix]) => `${UI_ART_DIR}/${name}${suffix}.png`),
    );
    expect([...files.keys()]).toEqual([...expected, `${UI_ART_DIR}/index.ts`]);
    expect(files.size).toBe(UI_ART_NAMES.length * 3 + 1);
  });

  it('renders transparent images of the point size times the scale', () => {
    for (const source of uiArtSources()) {
      for (const [suffix, scale] of SUFFIXES) {
        const info = readPngInfo(png(files, `${UI_ART_DIR}/${source.name}${suffix}.png`));
        expect(info.width).toBe(source.widthPt * scale);
        expect(info.height).toBe(source.heightPt * scale);
        expect(info.hasAlpha).toBe(true);
      }
    }
    const back2x = readPngInfo(png(files, `${UI_ART_DIR}/back@2x.png`));
    expect([back2x.width, back2x.height]).toEqual([48, 48]);
  });

  it('renders the same bytes every time', () => {
    const again = buildUiFiles();
    for (const [path, value] of files) expect(again.get(path), path).toEqual(value);
  });

  it('draws a different image per glyph', () => {
    const pngs = UI_ART_NAMES.map((name) => png(files, `${UI_ART_DIR}/${name}.png`));
    for (let i = 0; i < pngs.length; i++) {
      for (let j = i + 1; j < pngs.length; j++) expect(pngs[i]).not.toEqual(pngs[j]);
    }
  });

  it('writes the index module with every image, its key and its size', () => {
    const source = uiArtModuleSource();
    expect(files.get(`${UI_ART_DIR}/index.ts`)).toBe(source);
    expect(
      source.startsWith(
        '// Generated by tools/brand (npm run brand -- --targets ui) - do not edit.\n',
      ),
    ).toBe(true);
    expect(source).toContain(
      '/* eslint-disable @typescript-eslint/no-require-imports -- React Native static image requires */',
    );
    expect(source).toContain("import type { ImageSourcePropType } from 'react-native';");
    expect(source.match(/require\(/g)).toHaveLength(UI_ART_NAMES.length);
    for (const name of UI_ART_NAMES) expect(source).toContain(`require('./${name}.png')`);
    const keys = /export const UI_ART_KEYS = \[([^\]]*)\] as const;/.exec(source)?.[1] ?? '';
    expect([...keys.matchAll(/'([^']+)'/g)].map((m) => m[1])).toEqual(UI_ART_NAMES);
    expect(source).toContain('export type UiArt = (typeof UI_ART_KEYS)[number];');
    for (const s of uiArtSources()) {
      expect(source).toContain(`${s.name}: { width: ${s.widthPt}, height: ${s.heightPt} },`);
    }
    expect(source.endsWith('\n')).toBe(true);
  });
});
