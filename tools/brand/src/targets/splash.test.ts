import { UI_COLORS } from '@pn/design-tokens';
import { beforeAll, describe, expect, it } from 'vitest';

import { BRAND_MARK, markBounds } from '../mark';
import { OUTLINE_WIDTH } from '../palettes';
import { readPngInfo } from '../png';
import { assertWellFormedXml } from '../testing/xmlWellFormed';
import type { FileMap } from '../types';
import { buildSplashFiles, splashAndroidLogoPng, splashLogoDocument } from './splash';

const IOS = 'apps/mobile/ios/PocketNotes';
const RES = 'apps/mobile/android/app/src/main/res';
const BRAND = 'apps/mobile/src/brand';

describe('buildSplashFiles', () => {
  let files: FileMap;
  beforeAll(() => {
    files = buildSplashFiles();
  }, 120_000);

  const text = (path: string): string => {
    const value = files.get(path);
    if (typeof value !== 'string') throw new Error(`no text at ${path}`);
    return value;
  };
  const png = (path: string): Uint8Array => {
    const value = files.get(path);
    if (!(value instanceof Uint8Array)) throw new Error(`no PNG at ${path}`);
    return value;
  };

  it('writes iOS, Android and the JS module: 28 files', () => {
    expect(files.size).toBe(28);
    expect([...files.keys()].at(-1)).toBe(`${BRAND}/splash.ts`);
  });

  it('writes the iOS logo set at 1x/2x/3x, light and dark, the colour set and the storyboard', () => {
    for (const [suffix, px] of [
      ['', 128],
      ['@2x', 256],
      ['@3x', 384],
    ] as const) {
      for (const look of ['light', 'dark']) {
        const info = readPngInfo(
          png(`${IOS}/Images.xcassets/BootSplashLogo.imageset/logo-${look}${suffix}.png`),
        );
        expect(info).toMatchObject({ width: px, height: px, hasAlpha: true });
      }
    }
    const colours = JSON.parse(
      text(`${IOS}/Images.xcassets/BootSplashBackground.colorset/Contents.json`),
    );
    expect(colours.colors).toHaveLength(2);
    assertWellFormedXml(text(`${IOS}/LaunchScreen.storyboard`));
  });

  it('writes Android logos per density and night, and the background colours', () => {
    expect(readPngInfo(png(`${RES}/drawable-xxxhdpi/bootsplash_logo.png`)).width).toBe(1152);
    expect(readPngInfo(png(`${RES}/drawable-night-mdpi/bootsplash_logo.png`)).width).toBe(288);
    for (const values of ['values', 'values-night']) {
      expect(text(`${RES}/${values}/bootsplash.xml`)).toContain(
        `<color name="bootsplash_background">${UI_COLORS.bg}</color>`,
      );
    }
  });

  it('generates the splash module with the colours and the logo requires', () => {
    const source = text(`${BRAND}/splash.ts`);
    expect(source.startsWith('// Generated by tools/brand')).toBe(true);
    expect(source).toContain(`background: { light: '${UI_COLORS.bg}', dark: '${UI_COLORS.bg}' }`);
    expect(source).toContain("light: require('./splash-logo-light.png')");
    expect(files.has(`${BRAND}/splash-logo-dark@3x.png`)).toBe(true);
  });

  it('keeps the logo inside its 128 box with no ground', () => {
    const doc = splashLogoDocument('splashDark');
    expect(doc.palette.ground).toBeNull();
    expect(doc.placement.canvas).toBe(128);
    // Every outlined point of the mark, scaled and centred, stays inside the 128 box.
    const b = markBounds(BRAND_MARK);
    const k = doc.placement.markSize / 120;
    const pad = OUTLINE_WIDTH / 2;
    const offset = (128 - doc.placement.markSize) / 2;
    for (const v of [b.minX - pad, b.minY - pad]) expect(offset + v * k).toBeGreaterThanOrEqual(0);
    for (const v of [b.maxX + pad, b.maxY + pad])
      expect(offset + v * k).toBeLessThanOrEqual(128.01);
    expect(() => splashAndroidLogoPng('splashDark', 0.3)).toThrow(RangeError);
  });
});
