// Home: the pitch with the brand mark, the store badges and four feature cards.
import type { JSX } from 'react';
import type { SiteKey, SiteTranslator } from '@pn/i18n/site';

import { SITE_ORIGIN, STORE_LINKS } from '../config';
import type { RenderContext } from '../pages';
import { Section } from '../ui/Section';
import { StoreBadges } from '../ui/StoreBadges';
import styles from './Content.module.css';

const FEATURES: readonly (readonly [SiteKey, SiteKey])[] = Object.freeze([
  ['site.home.feature.dig.title', 'site.home.feature.dig.body'],
  ['site.home.feature.share.title', 'site.home.feature.share.body'],
  ['site.home.feature.offline.title', 'site.home.feature.offline.body'],
  ['site.home.feature.private.title', 'site.home.feature.private.body'],
]);

export function Home(props: { t: SiteTranslator; ctx: RenderContext }): JSX.Element {
  const { t } = props.t;
  return (
    <>
      <div className={`${styles.page ?? ''} ${styles.hero ?? ''}`.trim() || undefined}>
        <div className={styles.heroText}>
          <h1>{t('site.home.heading')}</h1>
          <p className={styles.lead}>{t('site.home.lead')}</p>
          <StoreBadges t={props.t} links={STORE_LINKS} placement="hero" />
        </div>
        {/* The brand mark, generated by `npm run brand -- --targets site` (tools/brand). */}
        <img
          className={styles.heroShot}
          src="/site/mark.svg"
          alt={t('site.home.heroAlt')}
          width={480}
          height={480}
          fetchPriority="high"
        />
      </div>
      <Section>
        <ul className={styles.cards}>
          {FEATURES.map(([title, body]) => (
            <li key={title} className={styles.card}>
              <h3>{t(title)}</h3>
              <p>{t(body)}</p>
            </li>
          ))}
        </ul>
      </Section>
      <Section id="get-the-app" heading={t('site.home.storeHeading')} tone="raised">
        <StoreBadges t={props.t} links={STORE_LINKS} placement="footer" />
      </Section>
    </>
  );
}

/** One WebSite object for the home page. */
export function homeJsonLd(t: SiteTranslator, ctx: RenderContext): readonly object[] {
  return [
    {
      '@context': 'https://schema.org',
      '@type': 'WebSite',
      name: t.t('site.meta.siteName'),
      description: t.t('site.meta.defaultDescription'),
      url: ctx.absoluteUrl('home'),
      inLanguage: ctx.locale,
      publisher: { '@type': 'Organization', name: t.t('site.meta.siteName'), url: SITE_ORIGIN },
    },
  ];
}
